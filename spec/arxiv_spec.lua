local arxiv = require("arxiv")

local function accepts(input, id)
    local got, err = arxiv.parse(input)
    assert.equal(id, got, "parse(" .. string.format("%q", input) .. ") err=" .. tostring(err))
end

local function rejects(input, code)
    local got, err = arxiv.parse(input)
    assert.equal(nil, got, "parse(" .. string.format("%q", input) .. ") should fail")
    if code then
        assert.equal(code, err, "error code for " .. string.format("%q", input))
    end
end

describe("arxiv.parse", function()
    it("accepts modern identifiers", function()
        accepts("2609.16338", "2609.16338")
        accepts("1501.00001", "1501.00001")
        accepts("0704.0001", "0704.0001")
        accepts("1412.9999", "1412.9999")
    end)

    it("preserves explicit versions", function()
        accepts("2609.16338v2", "2609.16338v2")
        accepts("0706.0001v12", "0706.0001v12")
        assert.equal("2609.16338v2.pdf", arxiv.filename(arxiv.parse("2609.16338v2")))
    end)

    it("trims whitespace and strips a case-insensitive arXiv: prefix", function()
        accepts(" arXiv:2609.16338 ", "2609.16338")
        accepts("\tARXIV:2609.16338v3\n", "2609.16338v3")
        accepts("arxiv:2609.16338", "2609.16338")
    end)

    it("accepts abs and pdf URLs on arxiv.org hosts", function()
        accepts("https://arxiv.org/abs/2609.16338", "2609.16338")
        accepts("https://arxiv.org/pdf/2609.16338", "2609.16338")
        accepts("https://arxiv.org/pdf/2609.16338.pdf", "2609.16338")
        accepts("https://arxiv.org/pdf/2609.16338v2.pdf", "2609.16338v2")
        accepts("http://arxiv.org/abs/2609.16338", "2609.16338")
        accepts("HTTPS://ArXiv.Org/abs/2609.16338", "2609.16338")
        accepts("https://www.arxiv.org/abs/2609.16338", "2609.16338")
        accepts("https://export.arxiv.org/abs/2609.16338v1", "2609.16338v1")
        accepts("https://arxiv.org/abs/2609.16338?context=cs", "2609.16338")
        accepts("https://arxiv.org/abs/2609.16338#section", "2609.16338")
        accepts("arxiv.org/abs/2609.16338", "2609.16338")
    end)

    it("rejects untrusted or look-alike hosts", function()
        rejects("https://arxiv.org.evil.test/abs/2609.16338", "untrusted_host")
        rejects("https://evil.test/pdf/2609.16338", "untrusted_host")
        rejects("http://evil/abs/2609.16338", "untrusted_host")
        rejects("https://arxiv.org@evil.test/abs/2609.16338", "untrusted_host")
        rejects("https://evil.test@arxiv.org/abs/2609.16338", "untrusted_host")
        rejects("https://arxiv.org:8443/abs/2609.16338", "untrusted_host")
        rejects("https://arxiv.org./abs/2609.16338", "untrusted_host")
        rejects("https://evilarxiv.org/abs/2609.16338", "untrusted_host")
        rejects("https://sub.arxiv.org/abs/2609.16338", "untrusted_host")
    end)

    it("rejects unsupported schemes and URL paths", function()
        rejects("ftp://arxiv.org/abs/2609.16338", "invalid_url")
        rejects("file:///abs/2609.16338", "invalid_url")
        rejects("javascript://arxiv.org/abs/2609.16338", "invalid_url")
        rejects("https://arxiv.org/list/2609.16338", "invalid_url")
        rejects("https://arxiv.org/2609.16338", "invalid_url")
        rejects("https://arxiv.org/abs/2609.16338/", "invalid_format")
        rejects("https://arxiv.org/abs/2609.16338.pdf", "invalid_format")
        rejects("https://arxiv.org/abs/../pdf/2609.16338")
        rejects("https://arxiv.org/abs/2609.16338/../../etc")
    end)

    it("rejects impossible months, widths and versions", function()
        rejects("2600.16338", "invalid_month")
        rejects("2613.16338", "invalid_month")
        rejects("2609.16338v0", "invalid_version")
        rejects("2609.16338v01", "invalid_version")
        rejects("2609.16338v", "invalid_version")
        rejects("2609.16338v2v3", "invalid_version")
        rejects("2609.1633", "invalid_number")   -- 4 digits after 1412
        rejects("2609.163380", "invalid_number") -- 6 digits
        rejects("1412.00001", "invalid_number")  -- 5 digits before 1501
        rejects("1501.0001", "invalid_number")   -- 4 digits after 1412
        rejects("2609.00000", "invalid_number")
        rejects("0612.1234", "unsupported_legacy") -- before the April 2007 scheme
        rejects("0703.1234", "unsupported_legacy")
    end)

    it("rejects traversal, separators and control characters", function()
        rejects("../../2609.16338")
        rejects("2609.16338/foo", "invalid_format")
        rejects("2609/16338", "invalid_format")
        rejects("2609.16338%2F..%2F", "invalid_characters")
        rejects("%2e%2e%2f2609.16338", "invalid_characters")
        rejects("2609.16338\0", "invalid_characters")
        rejects("2609.\n16338", "invalid_characters")
        rejects("2609.16338 v2", "invalid_characters")
        rejects("2609\\16338", "invalid_characters")
        rejects("2609.16338\226\128\139", "invalid_characters") -- zero-width space
        rejects("arXiv: 2609.16338", "invalid_characters")
        rejects("arXiv:arXiv:2609.16338", "invalid_format")
        rejects("2609.16338.pdf", "invalid_format")
        rejects(string.rep("1", 5000), "invalid_characters")
    end)

    it("reports legacy identifiers as unsupported", function()
        rejects("cs/9901001", "unsupported_legacy")
        rejects("math.GT/0309136", "unsupported_legacy")
        rejects("hep-th/9901001v2", "unsupported_legacy")
        rejects("https://arxiv.org/abs/cs/9901001", "unsupported_legacy")
    end)

    it("rejects empty and non-string input", function()
        rejects("", "empty")
        rejects("   ", "empty")
        rejects(nil, "empty")
        rejects(42, "empty")
    end)
end)

describe("arxiv URL and filename", function()
    it("builds only the canonical https endpoint", function()
        assert.equal("https://arxiv.org/pdf/2609.16338", arxiv.build_pdf_url("2609.16338"))
        assert.equal("https://arxiv.org/pdf/2609.16338v2", arxiv.build_pdf_url("2609.16338v2"))
    end)

    it("derives filenames from the normalized id only", function()
        local id = arxiv.parse("https://arxiv.org/pdf/2609.16338v2.pdf?download=../../x")
        assert.equal("2609.16338v2.pdf", arxiv.filename(id))
    end)
end)
